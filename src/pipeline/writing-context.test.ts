test('production research-to-writing bridge preserves Deep length, exact facts and one shared allowance without refetching', async () => {
  const root = mkdtempSync(join(tmpdir(), 'research-writing-'));
  const rich = JSON.parse(readFileSync(new URL('../../examples/fixtures/newsletter-rich-sports-evidence.json', import.meta.url), 'utf8')) as { topics: Array<EvidenceTopic & { sourceText: string }> };
  const request: WritingPreparationRequest = { parent: { root, parentId: 'sports', parentIdentity: roleHash('original sports request'), limits: { totalSeconds: 120, maxPhysicalCalls: 30, maxToolCalls: 24 } }, day: '2026-09-14', briefHash: roleHash('sports'), settingsHash: roleHash('exact writer'), selectedEvidenceHash: roleHash(rich), topics: rich.topics.map(({ sourceText: _, ...item }) => item), targets: { video: { min: 195, max: 220 }, newsletter: { min: 900, max: 1300 } }, fixedVideoWords: 20 };
  const http: string[] = [], tasks: string[] = [];
  const descriptors: PreparedModelTask[] = [];
  const adapters: TopicResearchAdapters = {
    request: async url => {
      http.push(url);
      if (url.includes('bing.com')) {
        const row = rich.topics.find(item => new URL(url).searchParams.get('q')?.includes(item.id))!;
        return new Response(`<a class="title" href="${row.primaryUrl}">Official source</a>`);
      }
      const row = rich.topics.find(item => item.primaryUrl === url)!;
      assert.ok(row, 'No unselected source can be fetched');
      return new Response(`<article>${row.sourceText}</article>`);
    },
    judge: async <T,>(prompt: string, validate: (value: T) => string | null, context: Parameters<TopicResearchAdapters['judge']>[2]) => {
      tasks.push(context.taskId);
      assertPreparedModelTask(context.task); descriptors.push(context.task);
      context.hooks.beforeAttempt!({ provider: 'ollama', model: 'fixture:4b', attempt: 1, rescue: false, promptBytes: Buffer.byteLength(prompt) });
      const value = context.task.capability === 'query-plan' ? { queries: rich.topics.map(item => ({ topicId: item.id, query: `${item.id} official schedule` })) }
        : context.task.capability === 'page-relevance' ? { sourceId: JSON.parse(prompt.split('FETCHED_SOURCE: ')[1]!).id, supported: true, reason: 'The original official source records the planned schedule and its limitations.' }
        : context.task.capability === 'evidence-review' ? (() => {
          const initial = JSON.parse(prompt.split('INITIAL_SELECTION: ')[1]!.split('\n')[0]!);
          return initial;
        })()
        : { selectedIds: JSON.parse(prompt.split('SOURCE_SENTENCES: ')[1]!).map((row: { id: number }) => row.id), requiredIds: [], unsupportedCandidate: [] };
      assert.equal(validate(value as T), null); return value as T;
    },
  };
  try {
    const result = await prepareResearchedWriting(request, adapters);
    assert.equal(result.status, 'ready'); if (result.status !== 'ready') return;
    assert.deepEqual(result.plan.targets, request.targets);
    assert.deepEqual(result.plan.topics.map(item => item.verifiedClaims.join(' ')), rich.topics.map(item => item.sourceText));
    assert.equal(http.length, 6, 'Three searches and three reads; preparation reuses the exact captured artifacts');
    assert.equal(result.parent.toolAttempts, 9); assert.equal(result.parent.physicalAttempts, 10);
    assert.deepEqual(descriptors.map(task => task.capability), ['query-plan', 'page-relevance', 'page-relevance', 'page-relevance', 'evidence-select', 'evidence-review', 'evidence-select', 'evidence-review', 'evidence-select', 'evidence-review']);
    assert.deepEqual(descriptors[0]!.topicIds, request.topics.map(topic => topic.id));
    for (const task of descriptors.slice(1)) assert.equal(task.topicIds.length, 1);
    assert.equal(descriptors[4]!.evidenceHash, descriptors[5]!.evidenceHash, 'initial and independent source selection bind the same full capture');
    const cached = await prepareResearchedWriting(request, adapters);
    assert.equal(cached.status, 'ready'); assert.equal(http.length, 6); assert.equal(tasks.length, 10);
    assert.equal(cached.parent.toolAttempts, 9); assert.equal(cached.parent.physicalAttempts, 10);
  } finally { rmSync(root, { recursive: true, force: true }); }
});


test('image visibility and save timestamps preserve editorial identity while actual writing choices remain bound', () => {
  const initial = { ...EMPTY_PERSONALIZATION, newsletterLength: 'deep' as const, styleNotes: 'Preserve concrete details', updatedAt: '2026-09-14T10:00:00.000Z' };
  const changedImages = { ...initial, newsletterImages: false, updatedAt: '2026-09-15T10:00:00.000Z' };
  assert.deepEqual(writingPersonalizationIdentity(changedImages), writingPersonalizationIdentity(initial));
  const old = { ...initial }; delete (old as Partial<typeof old>).newsletterImages;
  assert.deepEqual(writingPersonalizationIdentity(changedImages, old), old, 'Legacy timestamps retain their old hash slot without comparing the new presentation-save timestamp');
  assert.deepEqual(writingPersonalizationIdentity(changedImages, initial), initial, 'An existing parent that already bound the default image option retains its exact snapshot');
  assert.equal(roleHash(writingPersonalizationIdentity(changedImages, initial)), roleHash(initial), 'Legacy key order is part of the old exact parent hash');
  assert.equal(roleHash(writingPersonalizationIdentity(changedImages, old)), roleHash(old));
  for (const change of [{ newsletterLength: '' as const }, { styleNotes: 'Different prose style' }, { videoLength: 'standard' as const }, { format: 'conversation' as const }, { organization: 'New publisher' }]) {
    assert.notEqual(roleHash(writingPersonalizationIdentity({ ...changedImages, ...change }, old)), roleHash(old));
  }
});
