test('video-only source preparation never inherits a newsletter target or renews an existing output scope', () => {
  const video = { min: 195, max: 220 };
  assert.equal(writingOutputs(), 'video');
  assert.equal(writingOutputs({ outputs: 'edition' }), 'edition');
  assert.equal(writingOutputs(null, 'edition'), 'edition');
  for (const outputs of ['video', 'edition'] as const) {
    assert.equal(writingOutputs({ outputs }, outputs), outputs);
    assert.throws(() => writingOutputs({ outputs }, outputs === 'video' ? 'edition' : 'video'), /Start a new package.*budget cannot be renewed/);
  }
  assert.deepEqual(writingNewsletterTarget('video', 1, video, [900, 1300]), video);
  assert.deepEqual(writingNewsletterTarget('video', 1, video, [900, 1300], 20), { min: 175, max: 200 });
  assert.deepEqual(writingNewsletterTarget('edition', 4, video, [900, 1300]), { min: 900, max: 1300 });
  assert.deepEqual(writingNewsletterTarget('edition', 3, video), { min: 900, max: 1300 });
});

test('one direct source gets scene metadata without inventing verified facts or changing the selected topic', () => {
  for (const kind of ['news', 'repo'] as const) {
    const original: Topic = { id: '20260914-sports', kind, headline: 'Harbor match', angle: 'Sports coverage', primaryUrl: 'https://example.org/sports/match', sourceItems: [], alternates: [], repo: kind === 'repo' ? { fullName: 'league/results', stars: 0, url: 'https://github.com/league/results' } : null };
    const before = structuredClone(original), selected = selectedWritingStories(original);
    assert.deepEqual(original, before);
    assert.equal(selected.length, 1); assert.equal(selected[0]!.primaryUrl, original.primaryUrl);
    assert.equal(selected[0]!.assetRef, 'og-0');
    assert.equal(selected[0]!.verifiedClaims, undefined); assert.equal(selected[0]!.claimEvidence, undefined);
    assert.deepEqual(selectedWritingStories({ ...original, stories: selected }), selected);
    assert.throws(() => selectedWritingStories({ ...original, stories: [...selected, ...selected] }), /exactly its original source/);
    assert.throws(() => selectedWritingStories({ ...original, stories: [{ ...selected[0]!, primaryUrl: 'https://example.org/old-city' }] }), /exactly its original source/);
  }
  const selected = selectedWritingStories(topic);
  assert.deepEqual(selected, topic.stories); selected[0]!.headline = 'Changed copy';
  assert.equal(topic.stories![0]!.headline, 'Harbor match');
  assert.throws(() => selectedWritingStories({ ...topic, stories: [] }), /retain its selected stories/);
});
test('source enrichment retains its original request and rejects unrelated replacement facts', () => {
  const original = structuredClone(topic), prepared = structuredClone(topic);
  prepared.stories![0]!.verifiedClaims!.push('The report lists no injury assessment.');
  const saved = { original, originalHash: roleHash(original), preparedHash: roleHash(prepared) };
  assert.deepEqual(originalWritingTopic(original, saved), original);
  assert.deepEqual(originalWritingTopic(prepared, saved), original);
  assert.throws(() => originalWritingTopic({ ...prepared, headline: 'Old city activities' }, saved), /selected package changed/);
  const changed = structuredClone(saved); changed.original.stories![0]!.verifiedClaims = ['Unrelated replacement.'];
  assert.throws(() => originalWritingTopic(prepared, changed), /selected package changed/);
});

test('completed script reuse requires exact prepared evidence, writer settings and generated bytes', () => {
  const script = { body: [{ voiceover: 'The match ended level.' }] }, writerKey = 'exact model and current settings';
  const receipt = preparedScriptReceipt(topic, writerKey, script);
  assert.doesNotThrow(() => assertPreparedScriptReceipt(receipt, topic, writerKey, script));
  assert.throws(() => assertPreparedScriptReceipt(null, topic, writerKey, script), /not bound/);
  assert.throws(() => assertPreparedScriptReceipt(receipt, { ...topic, headline: 'Changed request' }, writerKey, script), /not bound/);
  assert.throws(() => assertPreparedScriptReceipt(receipt, topic, 'different writer', script), /not bound/);
  assert.throws(() => assertPreparedScriptReceipt(receipt, topic, writerKey, { body: [{ voiceover: 'The home side won.' }] }), /not bound/);
  const old = { version: 1, topicHash: receipt.topicHash, writerKey, scriptHash: receipt.scriptHash };
  assert.throws(() => assertPreparedScriptReceipt(old as unknown as PreparedScriptReceipt, topic, writerKey, script), /not bound/, 'identical content from the old unreviewed contract cannot be reused');
  for (const key of ['sourceSupportVersion', 'fieldSupportVersion', 'scriptReviewVersion'] as const) {
    assert.throws(() => assertPreparedScriptReceipt({ ...receipt, [key]: receipt[key] - 1 }, topic, writerKey, script), /not bound/);
  }
});

